/* Program to Demonstrate Bitwise XOR(^) Operators */

#include <stdio.h>

int main(void)
{
    int number1, number2;
    
    // Input numbers
    printf("Enter the values of two numbers ");
    scanf("%d %d", &number1, &number2);
    
    // Output numbers
    printf("Bitwise XOR: %d", number1 ^ number2);
    
    return 0;
  }  