/* Program to Demonstrate Bitwise OR(|) Operators */

#include <stdio.h>

int main(void)
{
    int number1, number2;
    
    // Input numbers
    printf("Enter the two values of numbers:");
    scanf("%d %d", &number1, &number2);
    
    // Output number
    printf("Bitwise OR(|): %d", number1 | number2);
    
    return 0;
  }  
    
    